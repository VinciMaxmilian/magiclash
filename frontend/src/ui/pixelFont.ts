const ACCENTS: Record<string, [string, string]> = {
  acute: ['...#.', '..#..'],
  grave: ['.#...', '..#..'],
  circ: ['..#..', '.#.#.'],
  tilde: ['.##.#', '#.##.'],
};

const ACCENTED: Record<string, [string, keyof typeof ACCENTS]> = {
  Á: ['A', 'acute'],
  À: ['A', 'grave'],
  Â: ['A', 'circ'],
  Ã: ['A', 'tilde'],
  É: ['E', 'acute'],
  Ê: ['E', 'circ'],
  Í: ['I', 'acute'],
  Ó: ['O', 'acute'],
  Ô: ['O', 'circ'],
  Õ: ['O', 'tilde'],
  Ú: ['U', 'acute'],
};

export const GLYPH_W = 5;
export const GLYPH_H = 10;

/** Returns 10 rows of 5 chars for `ch` (or `?` for unsupported chars). */
export const glyphRows = (ch: string): string[] => {
  const empty = '.....';
  if (ch === 'Ç') return [empty, empty, ...G.C, '..#..'];
  const acc = ACCENTED[ch];
  if (acc) return [...ACCENTS[acc[1]], ...G[acc[0]], empty];
  const g = G[ch] ?? G['?'];
  const body = g.slice(0, 7);
  const desc = g[7] ?? empty;
  return [empty, empty, ...body, desc];
};

export const FONT_CHARS = [
  ...Object.keys(G),
  'Ç',
  ...Object.keys(ACCENTED),
].join('');

/** Uppercases and replaces unsupported characters so any string renders safely. */
export const fontSafe = (text: string): string =>
  text
    .toUpperCase()
    .split('')
    .map((c) => (c === '\n' || FONT_CHARS.includes(c) ? c : '?'))
    .join('');
